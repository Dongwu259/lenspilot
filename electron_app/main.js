// Save binary data to temp directory — used by auto-update to stage installer
ipcMain.handle('save-temp-file', async (_, { data, filename }) => {
  // Sanitize filename to prevent path traversal (e.g. ../../../etc/passwd)
  const safeName = path.basename(filename || 'download.bin');
  if (!safeName || safeName === '.' || safeName === '..') {
    throw new Error('Invalid filename');
  }
  const dest = path.join(os.tmpdir(), safeName);
  // Reject payloads over 2GB to prevent disk exhaustion
  if (data && data.length > 2.8 * 1024 * 1024 * 1024) throw new Error('File too large');
  fs.writeFileSync(dest, Buffer.from(data, 'base64'));
  return dest;
});

// 校验安装包的 Authenticode 签名（仅 Windows）。fail-closed：
// 签名无效/未签名/校验过程本身出错，一律拒绝安装。
// SHA-256 与安装包同源于同一台服务器，服务器被攻破时哈希不可信，必须验签。
function verifyAuthenticodeSignature(filePath) {
  return new Promise((resolvePromise, reject) => {
    // PowerShell 单引号字符串内的单引号需双写转义
    const escaped = filePath.replace(/'/g, "''");
    execFile(
      'powershell',
      ['-NoProfile', '-NonInteractive', '-Command', `(Get-AuthenticodeSignature '${escaped}').Status`],
      { timeout: 15000 },
      (err, stdout) => {
        if (err) {
          reject(new Error(`无法验证安装包签名（${err.message}），已拒绝安装`));
          return;
        }
        if (stdout.trim() !== 'Valid') {
          reject(new Error('安装包签名无效或未签名，已拒绝安装'));
          return;
        }
        resolvePromise();
      }
    );
  });
}

// Launch downloaded installer and quit app. Only allows execution of files
// within the OS temp directory (where save-temp-file writes installers).
ipcMain.handle('install-and-quit', async (_, filePath) => {
  if (!filePath || typeof filePath !== 'string') throw new Error('Invalid path');
  const resolved = path.resolve(filePath);
  const tmpDir = path.resolve(os.tmpdir());
  // Must be *inside* temp: bare startsWith(tmpDir) also matches sibling paths
  // like "C:\Temp2\evil.exe" when tmpDir is "C:\Temp".
  if (!resolved.startsWith(tmpDir + path.sep)) throw new Error('Installer must be in temp directory');
  if (!fs.existsSync(resolved)) throw new Error('Installer file not found');
  // Windows 下先校验 Authenticode 签名再执行；macOS 走单独打包链（公证/dmg），此处跳过
  if (process.platform === 'win32') {
    try {
      await verifyAuthenticodeSignature(resolved);
    } catch (sigErr) {
      const msg = String((sigErr && sigErr.message) || sigErr);
      // 校验过程本身出错（PowerShell 不可用等）→ 保持 fail-closed
      if (msg.includes('无法验证')) throw sigErr;
      // 签名无效/未签名：当前发布用自签名证书（BUILD.md §代码签名），用户机
      // 默认不信任，fail-closed 会让自动更新全部死路。sha256 已在此前对
      // version.json 校验过完整性，这里给用户一次知情override。
      const { response } = await dialog.showMessageBox(mainWindow, {
        type: 'warning',
        buttons: ['取消', '仍要安装'],
        defaultId: 0,
        cancelId: 0,
        title: '安装包签名未受系统信任',
        message: '安装包未签名或签名证书不受信任',
        detail: 'LensPilot 当前使用自签名证书，Windows 默认不信任。\n'
          + '安装包已通过 SHA-256 完整性校验（与服务器发布值一致）。\n\n'
          + '如果你是从官网 studio.dwphoto.top 获取的本更新，可选择「仍要安装」；否则请取消。',
      });
      if (response !== 1) throw sigErr;
    }
  }
  shell.openPath(resolved);
  setTimeout(() => { stopPythonService(); app.quit(); }, 500);
  return true;
});

