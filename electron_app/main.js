ipcMain.handle('python-command', async (_, command, params) => {
  if (!ALLOWED_COMMANDS.has(command)) {
    throw new Error(`Command not allowed: ${command}`);
  }
  if (!pythonService || !pythonService.isRunning()) {
    throw new Error('Python backend is not running');
  }
  // Sandbox: destructive file operations require path validation
  const DESTRUCTIVE_CMDS = new Set(['rename_file', 'delete_file', 'apply_watermark', 'dedup_burst', 'clear_user_data', 'export_photos']);
  if (DESTRUCTIVE_CMDS.has(command)) {
    const pathsToCheck = [];
    if (params.oldPath) pathsToCheck.push(params.oldPath);
    if (params.newPath) pathsToCheck.push(params.newPath);
    if (params.path) pathsToCheck.push(params.path);
    if (params.paths) pathsToCheck.push(...(Array.isArray(params.paths) ? params.paths : []));
    if (params.file_paths) pathsToCheck.push(...(Array.isArray(params.file_paths) ? params.file_paths : []));
    for (const p of pathsToCheck) {
      if (typeof p !== 'string' || !p) continue;
      const resolved = path.resolve(p);
      // Reject paths targeting sensitive system locations
      const lower = resolved.toLowerCase();
      if (lower.startsWith('c:\\windows') || lower.startsWith('c:\\windows\\') ||
          lower === 'c:\\windows' || lower.startsWith('/system/') ||
          lower.startsWith('/etc/') || lower.startsWith('/bin/') ||
          lower.startsWith('/boot/') || lower.startsWith('/dev/') ||
          lower.startsWith('/usr/') || lower.startsWith('/var/') ||
          lower.startsWith('/lib/') || lower.startsWith('/lib64/') ||
          lower.startsWith('/proc/') || lower.startsWith('/sys/') ||
          lower.startsWith('/sbin/') || lower.startsWith('/opt/') ||
          lower.startsWith('/root/')) {
        throw new Error(`Blocked destructive operation on system path: ${p}`);
      }
    }
  }
  return pythonService.sendCommand(command, params);
});

// ── Secure Storage (safeStorage-encrypted localStorage substitute) ──
// Renderer calls these instead of direct localStorage for sensitive values
// (API keys, tokens). Falls back to base64 if safeStorage is unavailable.
function _secureStorePath() {
  return path.join(app.getPath('userData'), 'secure-store.json');
}

function _readSecureStore() {
  try {
    const p = _secureStorePath();
    if (fs.existsSync(p)) return JSON.parse(fs.readFileSync(p, 'utf-8'));
  } catch (_) { /* corrupted store → start fresh rather than crash */ }
  return {};
}

function _writeSecureStore(store) {
  // Atomic write: tmp file + rename, so a crash mid-write can't truncate the
  // store and lose every saved credential (was plain writeFileSync).
  const p = _secureStorePath();
  const tmp = p + '.tmp';
  fs.writeFileSync(tmp, JSON.stringify(store), 'utf-8');
  fs.renameSync(tmp, p);
}

let _warnedFallback = false;
function _encryptStoreValue(plain) {
  if (safeStorage.isEncryptionAvailable()) {
    return safeStorage.encryptString(plain).toString('base64');
  }
  // Fallback: base64 obfuscation (NOT encryption). Windows/macOS always have
  // safeStorage; this path is essentially Linux-without-keyring only.
  if (!_warnedFallback) {
    _warnedFallback = true;
    console.warn('[secure-store] safeStorage unavailable — secrets stored as base64, NOT encrypted');
  }
  return Buffer.from(plain, 'utf-8').toString('base64');
}

ipcMain.handle('secure-store-set', async (_, key, value) => {
  if (!key || typeof key !== 'string') throw new Error('Invalid key');
  const store = _readSecureStore();
  store[key] = _encryptStoreValue(String(value || ''));
  _writeSecureStore(store);
  return true;
});

ipcMain.handle('secure-store-get', async (_, key) => {
  if (!key || typeof key !== 'string') return null;
  const encrypted = _readSecureStore()[key];
  if (!encrypted) return null;
  try {
    if (safeStorage.isEncryptionAvailable()) {
      return safeStorage.decryptString(Buffer.from(encrypted, 'base64'));
    }
    // Fallback: base64 decode
    return Buffer.from(encrypted, 'base64').toString('utf-8');
  } catch (_) { return null; }
});

ipcMain.handle('secure-store-delete', async (_, key) => {
  if (!key || typeof key !== 'string') return false;
  const storePath = _secureStorePath();
  if (!fs.existsSync(storePath)) return false;
  const store = _readSecureStore();
  delete store[key];
  _writeSecureStore(store);
  return true;
});

