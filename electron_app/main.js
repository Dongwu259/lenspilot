// ── Portable mode ──
// If a 'data' directory exists next to the executable (Windows/Linux) or next
// to the .app bundle (macOS), store all user data there instead of the OS
// default (%APPDATA% / ~/Library/Application Support).
const appRoot = (() => {
  const exeDir = path.dirname(app.getPath('exe'));
  if (process.platform === 'darwin') {
    // macOS .app bundle: exeDir = LensPilot.app/Contents/MacOS
    // Go up 2 levels to get the .app dir, then up one more for the parent.
    return path.dirname(path.normalize(path.join(exeDir, '..', '..')));
  }
  return exeDir;
})();
const portableData = path.join(appRoot, 'data');
let pendingPortablePrompt = false;

if (fs.existsSync(portableData) && fs.statSync(portableData).isDirectory()) {
  app.setPath('userData', portableData);
  console.log('[main] portable mode — userData:', portableData);
} else if (process.platform !== 'darwin') {
  // Only show first-run portable prompt on Windows/Linux.
  // macOS has strict data-location conventions (~/Library/Application Support)
  // and apps inside .app bundles should be treated as read-only.
  const defaultUserData = app.getPath('userData');
  if (!fs.existsSync(defaultUserData)) {
    pendingPortablePrompt = true;
  }
}

// ── First-run login-state purge ──
// Each packaged build carries a buildId (build-id.json, generated by
// clean-before-build.py). On first launch of a given buildId we clear stored
// login state so a freshly distributed package never ships with the
// developer's credentials (e.g. a Windows portable that ran on the build
// machine leaving userData behind). Subsequent launches of the same buildId
// keep the user logged in.
async function purgeLoginStateIfNewBuild() {
  try {
    let buildId = 'unknown';
    const idFile = path.join(process.resourcesPath || __dirname, 'build-id.json');
    if (fs.existsSync(idFile)) {
      buildId = JSON.parse(fs.readFileSync(idFile, 'utf8')).buildId || 'unknown';
    }
    const userData = app.getPath('userData');
    const markerPath = path.join(userData, '.build-id');
    let lastBuildId = '';
    if (fs.existsSync(markerPath)) {
      lastBuildId = fs.readFileSync(markerPath, 'utf8').trim();
    }
    if (buildId !== lastBuildId) {
      // New build (or first ever launch) — wipe login/session storage.
      // Awaited before createWindow so the renderer never sees a stale token.
      console.log(`[main] new buildId (${buildId}), clearing login state + backend config`);
      const session = require('electron').session;
      try {
        await session.defaultSession.clearStorageData({ storages: ['localstorage', 'sessionstorage', 'cookies'] });
      } catch (e) { console.error('[main] clearStorageData failed:', e.message); }
      // Also purge backend credential files stored in userData (the Python
      // backend writes app_config.json / agent_usage.json / backend_pref.json
      // via APS_USER_DATA which maps to userData in packaged mode).
      for (const fn of ['app_config.json', 'agent_usage.json', 'backend_pref.json']) {
        try {
          const p = path.join(userData, fn);
          if (fs.existsSync(p)) { fs.rmSync(p); console.log(`[main] removed ${fn}`); }
        } catch (_) { /* best-effort */ }
      }
      fs.mkdirSync(userData, { recursive: true });
      fs.writeFileSync(markerPath, buildId, 'utf8');
    }
  } catch (e) {
    console.error('[main] purgeLoginStateIfNewBuild error:', e.message);
  }
}

