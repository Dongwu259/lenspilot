#!/usr/bin/env python3
"""
generate_luts.py — 生成 LensPilot 内置 .cube 调色 LUT 包

输出到 electron_app/python_backend/luts/(开发直用;打包经 --add-data 进 _MEIPASS/luts)。
全部由数学变换烘焙(无第三方 LUT 版权问题):饱和度/色阶/对比/分离色调/暖调的
组合,作用在 17^3 晶格上写出 Adobe .cube (LUT_3D_SIZE 17, red 最快轴)。

用法: python scripts/generate_luts.py
"""
import os
import numpy as np

SIZE = 17
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(HERE, "electron_app", "python_backend", "luts")


# ── 基础变换(全部作用于 (N,3) float32, [0,1]) ──

def _luma(rgb):
    return rgb[:, 0] * 0.2126 + rgb[:, 1] * 0.7152 + rgb[:, 2] * 0.0722


def saturation(rgb, k):
    l = _luma(rgb)[:, None]
    return l + (rgb - l) * k


def levels(rgb, black=(0.0, 0.0, 0.0), white=(1.0, 1.0, 1.0)):
    b = np.asarray(black, dtype=np.float32)
    w = np.asarray(white, dtype=np.float32)
    return rgb * (w - b) + b


def contrast(rgb, k):
    return 0.5 + (rgb - 0.5) * k


def split_tone(rgb, shadow_rgb, shadow_amt, high_rgb, high_amt):
    """阴影/高光着色:shadow_rgb/high_rgb 为加性偏移向量,按亮度平方掩膜加权。"""
    l = _luma(rgb)
    sm = ((1.0 - l) ** 2)[:, None] * shadow_amt
    hm = (l ** 2)[:, None] * high_amt
    return rgb + np.asarray(shadow_rgb, dtype=np.float32) * sm \
              + np.asarray(high_rgb, dtype=np.float32) * hm


def warmth(rgb, w):
    return rgb + np.asarray([w, 0.0, -w], dtype=np.float32)


def gain(rgb, g):
    return rgb * g


# ── LUT 配方 ──
# 每个配方是 lattice -> lattice 的函数,保持克制(交付级,不过度风格化)。

def recipe_warm_gold(rgb):
    """暖金婚礼:暖高光 + 柔对比 + 轻微降饱和,黑场一点点暖。"""
    rgb = levels(rgb, black=(0.012, 0.008, 0.004), white=(1.0, 0.985, 0.95))
    rgb = contrast(rgb, 1.06)
    rgb = saturation(rgb, 0.94)
    rgb = split_tone(rgb, shadow_rgb=(0.010, 0.004, -0.012), shadow_amt=0.5,
                     high_rgb=(0.045, 0.022, -0.030), high_amt=0.8)
    return rgb


def recipe_teal_orange(rgb):
    """青橙电影:阴影偏青、高光偏橙,对比与饱和略强。"""
    rgb = contrast(rgb, 1.10)
    rgb = saturation(rgb, 1.05)
    rgb = split_tone(rgb, shadow_rgb=(-0.022, 0.012, 0.030), shadow_amt=0.9,
                     high_rgb=(0.040, 0.010, -0.038), high_amt=0.9)
    return rgb


def recipe_muted_film(rgb):
    """低饱和胶片:黑场上提(fade)、降饱和、微绿中间调。"""
    rgb = levels(rgb, black=(0.045, 0.045, 0.042), white=(0.97, 0.97, 0.96))
    rgb = contrast(rgb, 0.96)
    rgb = saturation(rgb, 0.74)
    rgb = split_tone(rgb, shadow_rgb=(0.000, 0.008, 0.002), shadow_amt=0.6,
                     high_rgb=(0.012, 0.006, -0.010), high_amt=0.5)
    return rgb


def recipe_airy_fresh(rgb):
    """清新明亮:提亮、阴影上提、轻冷调,适合日系/亲子。"""
    rgb = gain(rgb, 1.06)
    rgb = levels(rgb, black=(0.020, 0.022, 0.026), white=(0.995, 0.995, 1.0))
    rgb = contrast(rgb, 0.97)
    rgb = saturation(rgb, 1.04)
    rgb = split_tone(rgb, shadow_rgb=(-0.006, 0.004, 0.016), shadow_amt=0.6,
                     high_rgb=(-0.006, 0.002, 0.014), high_amt=0.5)
    return rgb


def recipe_soft_portrait(rgb):
    """柔肤人像:柔对比 + 微暖 + 降饱和,肤色更奶。"""
    rgb = warmth(rgb, 0.012)
    rgb = contrast(rgb, 0.95)
    rgb = saturation(rgb, 0.92)
    rgb = split_tone(rgb, shadow_rgb=(0.008, 0.002, 0.004), shadow_amt=0.4,
                     high_rgb=(0.020, 0.006, 0.004), high_amt=0.6)
    return rgb


LUTS = [
    ("warm-gold", "LensPilot Warm Gold (婚礼暖金)", recipe_warm_gold),
    ("teal-orange", "LensPilot Teal & Orange (青橙电影)", recipe_teal_orange),
    ("muted-film", "LensPilot Muted Film (低饱和胶片)", recipe_muted_film),
    ("airy-fresh", "LensPilot Airy Fresh (清新明亮)", recipe_airy_fresh),
    ("soft-portrait", "LensPilot Soft Portrait (柔肤人像)", recipe_soft_portrait),
]


def _lattice():
    """17^3 晶格,(N,3) 顺序 b 外 / g 中 / r 内(red 最快轴,符合 .cube 规范)。"""
    axis = np.linspace(0.0, 1.0, SIZE, dtype=np.float32)
    pts = np.zeros((SIZE ** 3, 3), dtype=np.float32)
    i = 0
    for b in axis:
        for g in axis:
            for r in axis:
                pts[i] = (r, g, b)
                i += 1
    return pts


def write_cube(path, title, table):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f'TITLE "{title}"\n')
        f.write("# Generated by scripts/generate_luts.py (LensPilot builtin LUT pack)\n")
        f.write(f"LUT_3D_SIZE {SIZE}\n")
        for r, g, b in table:
            f.write(f"{r:.6f} {g:.6f} {b:.6f}\n")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    lat = _lattice()
    for slug, title, fn in LUTS:
        out = np.clip(fn(lat.copy()), 0.0, 1.0)
        path = os.path.join(OUT_DIR, f"{slug}.cube")
        write_cube(path, title, out)
        print(f"  {slug}.cube  ({SIZE}^3, {len(out)} 行)")


if __name__ == "__main__":
    main()
